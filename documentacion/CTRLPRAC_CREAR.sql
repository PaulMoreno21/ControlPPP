/*
  CTRLPRAC_CREAR.sql - esquema consolidado de Control PPP al 29/10/2026.
  Ejecutar UNA VEZ como propietario de un esquema Oracle VACIO, con permisos
  CREATE TABLE, CREATE SEQUENCE y CREATE TRIGGER y cuota en su tablespace.
  En Docker se ejecuta con SQL*Plus y se detiene ante el primer error.

  Incluye tablas, restricciones, triggers, secuencias, comentarios, roles base,
  tipo de cuenta, cambio obligatorio de clave, auditoria de accesos sin cuenta
  y los cuatro indices compuestos de rendimiento preparados para esta version.
  Estos cuatro indices estaban propuestos y no aplicados en la base local al
  realizar el contraste del 29/10/2026; aqui se crean para instalaciones nuevas.

  Conserva entrada y salida en el mismo dia y una sola asignacion vigente por
  practicante. El cierre automatico a las seis horas lo ejecuta la aplicacion;
  crear el esquema no instala tareas programadas en Oracle.

  No requiere ejecutar los archivos MIGRACION para una instalacion nueva.
  No borra objetos ni modifica la base existente. No crea usuarios de Oracle
  ni una cuenta de acceso a la aplicacion. Despues de este script, usar
  Crear_Admin_General_DBeaver.sql para crear el primer Administrador General.
  No contiene datos anteriores, credenciales ni contrasenas por defecto.
*/

DECLARE
  v_objects NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_objects
  FROM USER_OBJECTS
  WHERE OBJECT_TYPE IN ('TABLE', 'SEQUENCE', 'TRIGGER', 'INDEX')
    AND OBJECT_NAME NOT LIKE 'BIN$%';
  IF v_objects > 0 THEN
    RAISE_APPLICATION_ERROR(-20020,
      'Este script requiere un esquema vacio. Detenga la ejecucion y revise la conexion.');
  END IF;
END;
/

