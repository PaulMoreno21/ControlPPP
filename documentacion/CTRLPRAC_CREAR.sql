/*
  Reglas que consultan otras tablas se implementan con triggers. TO_CHAR usa
  idioma explicito para que la validacion del fin de semana no dependa de NLS.
*/
CREATE OR REPLACE TRIGGER TR_CWASISLAB
BEFORE INSERT OR UPDATE OF TCWASISTENCIAS_FECHA ON TCWASISTENCIAS
FOR EACH ROW
DECLARE
  V_FERIADOS NUMBER(1);
  V_DIA      VARCHAR2(3);
BEGIN
  V_DIA := UPPER(TO_CHAR(:NEW.TCWASISTENCIAS_FECHA, 'DY',
                         'NLS_DATE_LANGUAGE=ENGLISH'));
  IF V_DIA IN ('SAT', 'SUN') THEN
    RAISE_APPLICATION_ERROR(-20001,
      'No se permite registrar asistencia en fines de semana.');
  END IF;

  SELECT COUNT(*) INTO V_FERIADOS
    FROM TCWFERIADOS
   WHERE TCWFERIADOS_FECHA = :NEW.TCWASISTENCIAS_FECHA
     AND TCWFERIADOS_ACTIVO = 1;

  IF V_FERIADOS > 0 THEN
    RAISE_APPLICATION_ERROR(-20002,
      'No se permite registrar asistencia en un dia feriado.');
  END IF;
END;
/

/* Solo usuarios con rol ADMIN_GENERAL pueden crear o modificar feriados. */
CREATE OR REPLACE TRIGGER TR_CWFERADMIN
BEFORE INSERT OR UPDATE OF TCWUSUARIOS_ID_ADMIN ON TCWFERIADOS
FOR EACH ROW
DECLARE
  V_ES_ADMIN NUMBER(1);
BEGIN
  SELECT COUNT(*) INTO V_ES_ADMIN
    FROM TCWUSUARIOSROLES UR
    JOIN TCWROLES R ON R.TCWROLES_ID = UR.TCWROLES_ID
   WHERE UR.TCWUSUARIOS_ID = :NEW.TCWUSUARIOS_ID_ADMIN
     AND R.TCWROLES_NOMBRE = 'ADMIN_GENERAL';

  IF V_ES_ADMIN = 0 THEN
    RAISE_APPLICATION_ERROR(-20003,
      'Solo un ADMIN_GENERAL puede registrar dias feriados.');
  END IF;
END;
/

